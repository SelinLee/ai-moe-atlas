import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { readFile, mkdir } from 'node:fs/promises';
const origin = process.env.ATLAS_TEST_URL ?? 'http://127.0.0.1:4322/ai-moe-atlas';
const manifestPath = process.env.ATLAS_MODEL_MANIFEST ?? 'content/models/deep-whale-maid.json';
const model = JSON.parse(await readFile(manifestPath, 'utf8'));
const executablePath = process.env.CHROME_PATH;
const browser = await chromium.launch(executablePath ? { executablePath, headless: true } : { channel: 'chrome', headless: true });
await mkdir('.qa', { recursive: true });
const errors = [];
try {
  for (const lang of ['zh', 'en', 'ja']) {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
    const page = await context.newPage();
    page.on('pageerror', error => errors.push(error.message));
    const requests = [];
    page.on('request', request => requests.push(request.url()));
    await page.goto(`${origin}/${lang}/characters/${model.characterId}/`);
    await page.locator('#model-preview').scrollIntoViewIfNeeded();
    assert.equal(await page.locator('[data-model-preview]').count(), 1);
    assert.equal(await page.locator('model-viewer').count(), 0);
    assert.equal(requests.some(url => /\.glb(?:\?|$)|model-viewer.*\.js/.test(url)), false, 'Renderer and GLB are click-only');
    assert.equal(await page.locator('[data-model-controls]').isVisible(), false);
    await page.locator('[data-model-load]').focus();
    await page.keyboard.press('Enter');
    await page.waitForFunction(() => document.querySelector('[data-model-preview]')?.dataset.state === 'ready', undefined, { timeout: 45000 });
    const viewer = page.locator('model-viewer');
    assert.equal(await viewer.getAttribute('auto-rotate'), null);
    assert.equal(await viewer.getAttribute('autoplay'), null);
    assert.equal(await viewer.getAttribute('interpolation-decay'), '0');
    assert.equal(await viewer.evaluate(element => element.loaded), true);
    assert.equal(await page.locator('[data-model-controls]').isVisible(), true);
    assert.equal(await page.locator('[data-model-action="left"]').evaluate(element => element === document.activeElement), true);
    const initial = await viewer.evaluate(element => ({ ...element.getCameraOrbit() }));
    await page.locator('[data-model-action="left"]').click();
    await page.waitForFunction(theta => Math.abs(document.querySelector('model-viewer').getCameraOrbit().theta - theta) > .1, initial.theta);
    await page.locator('[data-model-action="in"]').click();
    await page.waitForFunction(radius => document.querySelector('model-viewer').getCameraOrbit().radius < radius * .9, initial.radius);
    await page.locator('[data-model-action="up"]').click();
    await page.waitForFunction(phi => document.querySelector('model-viewer').getCameraOrbit().phi < phi - .1, initial.phi);
    await page.locator('[data-model-action="reset"]').click();
    await page.waitForFunction(initial => { const orbit = document.querySelector('model-viewer').getCameraOrbit(); return Math.abs(orbit.theta-initial.theta)<.01 && Math.abs(orbit.phi-initial.phi)<.01 && Math.abs(orbit.radius-initial.radius)<.01; }, initial);
    assert.equal(await viewer.evaluate(element => element.a11y.front), { zh:'正面', en:'Front', ja:'正面' }[lang]);
    await page.locator('#model-preview').screenshot({ path:`.qa/model-${lang}-desktop.png` });
    await page.setViewportSize({ width:390, height:844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false);
    await page.locator('.model-interaction').screenshot({ path:`.qa/model-${lang}-mobile.png` });
    await page.locator('[data-model-unload]').click();
    assert.equal(await page.locator('model-viewer').count(), 0);
    assert.equal(await page.locator('[data-model-poster]').isVisible(), true);
    assert.equal(await page.locator('[data-model-load]').evaluate(element => element === document.activeElement), true);
    // A stopped preview is deliberately reloadable, including after a failed transfer.
    await page.route('**/*.glb', route => route.fulfill({ status:503, body:'Temporary failure' }));
    await page.reload();
    await page.locator('[data-model-load]').click();
    await page.waitForFunction(() => document.querySelector('[data-model-preview]')?.dataset.state === 'error');
    assert.equal(await page.locator('[data-model-poster]').isVisible(), true);
    assert.equal(await page.locator('[data-model-load]').isEnabled(), true);
    assert.equal(await page.locator('[data-model-controls]').isVisible(), false);
    await page.unroute('**/*.glb');
    await page.locator('[data-model-load]').click();
    await page.waitForFunction(() => document.querySelector('[data-model-preview]')?.dataset.state === 'ready', undefined, { timeout:45000 });
    // Other detail routes and the AI-family /models index keep their existing semantics.
    await page.goto(`${origin}/${lang}/`);
    assert.ok(await page.locator('.model-highlight').count() >= 1);
    assert.equal(await page.locator('model-viewer').count(), 0);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false);
    await page.locator('.model-highlight').screenshot({ path:`.qa/model-highlight-${lang}-mobile.png` });
    await page.goto(`${origin}/${lang}/models/`);
    assert.equal(await page.locator('[data-baseline]').count(), 12);
    assert.equal(await page.locator('model-viewer').count(), 0);
    await context.close();
    console.log(`3D preview: ${lang} desktop, mobile, lazy loading, controls, still image, failure/retry passed`);
  }
  const noScript = await browser.newContext({ javaScriptEnabled:false, viewport:{width:390,height:844} });
  const staticPage = await noScript.newPage();
  await staticPage.goto(`${origin}/en/characters/${model.characterId}/`);
  assert.equal(await staticPage.locator('[data-model-poster]').isVisible(), true);
  assert.equal(await staticPage.locator('[data-model-load]').isVisible(), false);
  assert.equal(await staticPage.locator('#model-preview noscript').isVisible(), true);
  await noScript.close();
  assert.deepEqual(errors, []);
  console.log('3D preview: no-JavaScript fallback and uncaught-error check passed');
} finally { await browser.close(); }
